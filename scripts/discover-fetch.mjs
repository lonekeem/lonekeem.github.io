#!/usr/bin/env node
// Builds data/discover.json from the curated list in data/discover-sources.json.
// Uses only public RSS/Atom feeds (YouTube channel feeds need no API key). Nothing is downloaded or
// re-uploaded: we keep video ids (shown as youtube-nocookie embeds) and headline links to the original.
// Run: node scripts/discover-fetch.mjs   (Node 18+). The GitHub Action runs it on a schedule.
import fs from 'node:fs';
const root = new URL('..', import.meta.url).pathname;
const cfg = JSON.parse(fs.readFileSync(root + 'data/discover-sources.json', 'utf8'));
const now = Date.now(), maxAge = (cfg.maxAgeDays || 45) * 864e5;
const words = (cfg.blockWords || []).map((w) => w.toLowerCase());
const esc = (w) => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const blockRe = new RegExp('(^|[^a-z])(' + words.map(esc).join('|') + ')([^a-z]|$)', 'i');
const unent = (s) => String(s || '').replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1').replace(/<[^>]+>/g, ' ')
  .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n)).replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
  .replace(/&quot;/g, '"').replace(/&apos;|&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&')
  .replace(/\s+/g, ' ').trim();
const tag = (xml, t) => { const m = xml.match(new RegExp(`<${t}(?:\\s[^>]*)?>([\\s\\S]*?)</${t}>`, 'i')); return m ? m[1] : ''; };
const attr = (xml, t, a) => { const m = xml.match(new RegExp(`<${t}\\s[^>]*${a}="([^"]+)"`, 'i')); return m ? m[1] : ''; };
const safe = (...t) => !blockRe.test(t.join(' '));
const clip = (s, n) => (s.length > n ? s.slice(0, n - 1).replace(/\s+\S*$/, '') + '…' : s);
async function get(url) {
  const r = await fetch(url, { headers: { 'user-agent': 'KemyDiscover/1.0 (+https://lonekeem.github.io/)' } });
  if (!r.ok) throw new Error(r.status + ' ' + url);
  return r.text();
}
const out = { updatedAt: new Date().toISOString(), note: 'Generated by scripts/discover-fetch.mjs from data/discover-sources.json. Do not edit by hand.', videos: [], news: [] };
let skipped = 0, shortsN = 0; const seen = new Set();
for (const ch of cfg.youtube || []) {
  try {
    const xml = await get('https://www.youtube.com/feeds/videos.xml?channel_id=' + encodeURIComponent(ch.channelId));
    const entries = xml.split('<entry>').slice(1).map((e) => {
      const id = tag(e, 'yt:videoId'), title = unent(tag(e, 'title')), pub = Date.parse(tag(e, 'published'));
      const desc = unent(tag(e, 'media:description')), views = +attr(e, 'media:statistics', 'views') || 0;
      const link = attr(e, 'link', 'href');
      return { id, title, pub, desc, views, short: /\/shorts\//.test(link) };
    }).filter((v) => /^[\w-]{11}$/.test(v.id) && v.pub && now - v.pub < maxAge);
    let n = 0;
    for (const v of entries) {
      if (n >= (ch.max || cfg.maxPerChannel || 6)) break;
      if (!safe(v.title, v.desc.slice(0, 300))) { skipped++; continue; }
      if (seen.has(v.id)) continue; seen.add(v.id);
      out.videos.push({ id: v.id, title: clip(v.title, 140), channel: ch.name, channelId: ch.channelId, cat: ch.cat, published: new Date(v.pub).toISOString(), views: v.views, short: v.short });
      n++;
    }
    console.log(`youtube ${ch.name}: ${n}`);
  } catch (e) { console.log(`youtube ${ch.name}: FAILED ${e.message}`); }
  // Shorts-only uploads: the public "UUSH" playlist feed (channel id without the leading "UC"). No API key.
  if (ch.shorts === false) continue;
  try {
    const xml = await get('https://www.youtube.com/feeds/videos.xml?playlist_id=UUSH' + encodeURIComponent(ch.channelId.replace(/^UC/, '')));
    let n = 0;
    for (const e of xml.split('<entry>').slice(1)) {
      if (n >= (ch.maxShorts || cfg.maxShortsPerChannel || 5)) break;
      const id = tag(e, 'yt:videoId'), title = unent(tag(e, 'title')), pub = Date.parse(tag(e, 'published'));
      const desc = unent(tag(e, 'media:description')), views = +attr(e, 'media:statistics', 'views') || 0;
      if (!/^[\w-]{11}$/.test(id) || !pub || now - pub > maxAge || seen.has(id)) continue;
      if (!safe(title, desc.slice(0, 300))) { skipped++; continue; }
      seen.add(id);
      out.videos.push({ id, title: clip(title, 140), channel: ch.name, channelId: ch.channelId, cat: ch.cat, published: new Date(pub).toISOString(), views, short: true, shorts: true });
      n++; shortsN++;
    }
    console.log(`shorts ${ch.name}: ${n}`);
  } catch (e) { console.log(`shorts ${ch.name}: FAILED ${e.message}`); }
}
for (const f of cfg.news || []) {
  try {
    const xml = await get(f.url);
    const items = (xml.includes('<item') ? xml.split(/<item[\s>]/) : xml.split('<entry>')).slice(1);
    let n = 0;
    for (const it of items) {
      if (n >= (f.max || 8)) break;
      const title = unent(tag(it, 'title'));
      let url = unent(tag(it, 'link')) || attr(it, 'link', 'href');
      const summary = clip(unent(tag(it, 'description') || tag(it, 'summary')), 220);
      const pub = Date.parse(tag(it, 'pubDate') || tag(it, 'published') || tag(it, 'updated')) || now;
      const image = attr(it, 'media:thumbnail', 'url') || attr(it, 'media:content', 'url') || attr(it, 'enclosure', 'url') || '';
      if (!title || !/^https:\/\//.test(url) || now - pub > maxAge) continue;
      if (!safe(title, summary)) { skipped++; continue; }
      out.news.push({ title: clip(title, 160), url, source: f.name, site: f.site, summary, image: /^https:\/\//.test(image) ? image : '', published: new Date(pub).toISOString() });
      n++;
    }
    console.log(`news ${f.name}: ${n}`);
  } catch (e) { console.log(`news ${f.name}: FAILED ${e.message}`); }
}
// Drop videos whose owners turned off embedding (they'd show "Video unavailable" instead of autoplaying).
{
  const keep = [];
  for (const v of out.videos) {
    try { const r = await fetch(`https://www.youtube.com/oembed?format=json&url=${encodeURIComponent('https://www.youtube.com/watch?v=' + v.id)}`); if (r.ok) keep.push(v); else skipped++; }
    catch { keep.push(v); }
  }
  console.log(`embeddable: ${keep.length}/${out.videos.length}`); out.videos = keep;
}
out.videos.sort((a, b) => b.published.localeCompare(a.published));
out.news.sort((a, b) => b.published.localeCompare(a.published));
console.log(`total: ${out.videos.length} videos (${shortsN} Shorts), ${out.news.length} headlines, ${skipped} skipped by the kid-safe filter`);
if (!out.videos.length && !out.news.length) { console.log('Nothing fetched; keeping the old file.'); process.exit(0); }
fs.writeFileSync(root + 'data/discover.json', JSON.stringify(out, null, 1) + '\n');
